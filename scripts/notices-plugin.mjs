function packageOf(id) {
	const parts = id.split(/[\\/]/)
	const i = parts.lastIndexOf('node_modules')
	if (i < 0) return null
	return parts[i + 1].startsWith('@') ? `${parts[i + 1]}/${parts[i + 2]}` : parts[i + 1]
}

function licenseText(dir) {
	const file = readdirSync(dir).find((f) => /^(licen[cs]e|copying)(\.(md|txt))?$/i.test(f))
	return file ? readFileSync(join(dir, file), 'utf8').trim() : null
}

export function thirdPartyNotices() {
	return {
		name: 'third-party-notices',
		apply: 'build',
		generateBundle() {
			const names = new Set(Object.keys(EXTRA))
			for (const id of this.getModuleIds()) {
				const name = packageOf(id.replace(/^\0/, '').split('?')[0])
				if (name) names.add(name)
			}
			const sections = []
			for (const name of [...names].sort()) {
				const dir = join(root, 'node_modules', ...name.split('/'))
				if (!existsSync(join(dir, 'package.json'))) continue
				const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'))
				let text = licenseText(dir)
				if (!text && pkg.license === 'MIT' && MISSING_LICENSE_FILE[name]) {
					text = ['The MIT License (MIT)', MISSING_LICENSE_FILE[name], MIT].join('\n\n')
				}
				sections.push([
					`## ${name} ${pkg.version}`,
					'',
					`License: ${pkg.license ?? 'see below'}` + (pkg.homepage ? `  \nHomepage: ${pkg.homepage}` : ''),
					EXTRA[name] ? `Used for: ${EXTRA[name]}` : '',
					'',
					text ? '```\n' + text + '\n```' : `(no license file in the package; license field: ${pkg.license})`,
				].filter((l, i, a) => l !== '' || a[i - 1] !== '').join('\n'))
			}
			const head = [
				'# Third-party notices',
				'',
				'The built app (`js/groceries-main.js`, `css/groceries-main.css`) contains code or data from the',
				'following open source packages. This file is generated by `npm run build`',
				`(scripts/notices-plugin.mjs); ${sections.length} packages.`,
				'',
				'Emoji are drawn by the device\'s system font; no emoji images are bundled.',
				'',
				'The optional fonts for item names (`src/assets/fonts/`, built into `js/assets/`) are listed',
				'at the end.',
				'',
			].join('\n')
			const fontDir = join(root, 'src/assets/fonts')
			const fonts = [
				...[['Patrick Hand', 'PatrickHand-Regular.ttf', 'PatrickHand-OFL.txt'], ['Quicksand', 'Quicksand-Bold.ttf', 'Quicksand-OFL.txt']]
					.flatMap(([name, file, license], i) => [
						...(i ? [''] : []),
						`## Font: ${name}`,
						'',
						`License: OFL-1.1  `,
						`File: \`${file}\``,
						'',
						'```\n' + readFileSync(join(fontDir, license), 'utf8').trim() + '\n```',
					]),
			].join('\n')
			writeFileSync(join(root, 'THIRD-PARTY-NOTICES.md'), head + '\n' + sections.join('\n\n') + '\n\n' + fonts + '\n')
		},
	}
}

