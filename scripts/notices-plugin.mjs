/**
 * Vite plugin: writes THIRD-PARTY-NOTICES.md with the license of every npm package that actually
 * ends up in the built bundle (the licenses of these packages require their notice to travel with
 * copies of the code). Runs on every `vite build`.
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')

/** Packages whose data is bundled without being imported from node_modules at build time. */
const EXTRA = {
	'unicode-emoji-json': 'emoji list and groups in src/lib/emoji-groups.json (generated by scripts/build-emoji.mjs)',
}

